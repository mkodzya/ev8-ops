def q(who, why, s='', acts='', tone=''):
    sm = f'<div class="q-sum">{s}</div>' if s else ''
    a = f'<div class="q-acts">{acts}</div>' if acts else ''
    tone = ' '.join('t-'+t for t in tone.split()) + ('' if s else ' nosum')
    return f'<div class="qrow {tone}"><div class="q-who">{who}</div>{sm}<div class="q-why">{why}</div>{a}</div>'

