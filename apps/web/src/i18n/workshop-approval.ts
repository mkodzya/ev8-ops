/** How long something has waited: minutes, then hours and minutes, then days. */
const span = (min: number, m: string, h: string, d: (n: number) => string): string => {
  if (min < 60) return `${Math.max(0, min)} ${m}`;
  if (min < 24 * 60) return `${Math.floor(min / 60)} ${h}${min % 60 ? ` ${min % 60} ${m}` : ''}`;
  return d(Math.floor(min / (24 * 60)));
};

