#!/bin/bash
# The pilot stand: the one EV8 Ops on this Mac that may be shown to somebody
# who is not sitting at it — Kardu on his phone, before there is a server.
#
#   scripts/pilot-stand.sh up      empty database, the people, start it
#   scripts/pilot-stand.sh tunnel  open a fresh public link to it, print the link
#   scripts/pilot-stand.sh down    stop it and the tunnel (the database stays)
#   scripts/pilot-stand.sh status  what is running
#
# **It is empty of content on purpose** (Mika, 22.09.2026): Mika and Kardu
# fill it themselves — a model, a point, a moped, a customer, a hand-over —
# which is both the pilot and the training. Nothing of the real business is
# behind a public link: no customers, no rentals, no payments, no personal
# numbers. The only rows carried over from the laptop stand are the **people
# who sign in**, with the passwords they already use, so nobody has to invent
# or be told a new one.
#
# **Why the QA stand would not do.** Both other stands on this Mac run the
# laptop stack, where `ALLOW_DEV_SECRET=true`. That one flag accepts the
# development session secret *and* lets the demo logins in — and the demo
# dataset carries `demo.director@ev8.test`, an **owner**, whose password is
# published in this repository. Reachable from the internet over live data,
# that is not a pilot, it is a leak.
#
# So the pilot runs the overlay a real stand runs (`docker-compose.stand.yml`):
# no development secret, demo logins refused, nothing seeded. The demo
# accounts are not carried over at all.
#
# It listens on 127.0.0.1 only, like the QA stand — reachable from this Mac
# and from nothing else. What carries it further is a tunnel, attached either
# to that loopback port or to the compose network by name.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LIVE_PROJECT=ev8-ops-platform
PILOT_PROJECT=ev8-ops-pilot
DB_USER=ev8ops
DB_NAME=ev8ops
ENV_FILE="$ROOT/deploy/pilot.env"

live() { docker compose -p "$LIVE_PROJECT" -f "$ROOT/docker-compose.yml" "$@"; }
pilot() { docker compose -p "$PILOT_PROJECT" -f "$ROOT/docker-compose.yml" -f "$ROOT/docker-compose.stand.yml" --env-file "$ENV_FILE" "$@"; }

make_env() {
  [ -f "$ENV_FILE" ] && return
  echo "pilot: generating deploy/pilot.env (it is in .gitignore and stays on this Mac)"
  cat > "$ENV_FILE" <<ENV
# The pilot stand on this Mac. Generated by scripts/pilot-stand.sh.
# Machine secrets, never typed by a person and never committed.
POSTGRES_PASSWORD=$(openssl rand -base64 36 | tr -d '/+=')
SESSION_SECRET=$(openssl rand -base64 48)
WORKER_TOKEN=$(openssl rand -base64 48)
# The stand overlay asks for these, and nothing uses them: the database is a
# copy and already has its people, so the seed (--if-empty) does nothing.
# Mika signs in with his own password, exactly as he does on the other stands.
OWNER_EMAIL=nobody@ev8.invalid
OWNER_PASSWORD=$(openssl rand -base64 36)
# The hostnames vite answers to. Add whatever name the tunnel gives this
# stand — a wrong one here shows "Blocked request" and nothing else.
ALLOWED_HOSTS=127.0.0.1,localhost
WEB_PORT=5195
TZ=Asia/Tbilisi
DEFAULT_LOCALE=ka
ENV
}

take_images() {
  for svc in api worker web; do
    docker image inspect "$LIVE_PROJECT-$svc" >/dev/null 2>&1 || {
      echo "No image $LIVE_PROJECT-$svc: start the laptop stand once with --build." >&2
      exit 1
    }
    docker tag "$LIVE_PROJECT-$svc" "$PILOT_PROJECT-$svc"
  done
}

empty_database() {
  pilot stop api worker web >/dev/null 2>&1 || true
  pilot up -d --wait db
  pilot exec -T db psql -U "$DB_USER" -d postgres -v ON_ERROR_STOP=1 \
    -c "DROP DATABASE IF EXISTS $DB_NAME WITH (FORCE)" -c "CREATE DATABASE $DB_NAME"
  # The API's own entrypoint runs the migrations on first boot, so the stand
  # comes up with the tables, the settings migration 0029 wrote (deposit 180,
  # one quick rate of 150) and nothing else.
}

copy_the_people() {
  # The people who sign in, and only them: the row carries the password hash,
  # so everybody uses the password they already have and nobody invents one.
  # Demo logins are left behind — see the note at the top of this file.
  live exec -T db pg_isready -U "$DB_USER" -d "$DB_NAME" >/dev/null || {
    echo "The laptop stand's database is not running: docker compose up -d db" >&2
    exit 1
  }
  local sql
  sql=$(live exec -T db psql -U "$DB_USER" -d "$DB_NAME" -tAc "
    SELECT 'INSERT INTO users (id, email, name, password_hash, role, locale, active) VALUES ('
        || quote_literal(id::text) || '::uuid, '
        || quote_literal(email) || ', '
        || quote_literal(name) || ', '
        || quote_literal(password_hash) || ', '
        || quote_literal(role::text) || '::user_role, '
        || quote_literal(locale) || ', true) ON CONFLICT (id) DO NOTHING;'
    FROM users
    WHERE active AND email NOT LIKE '%@ev8.test'")
  [ -n "$sql" ] || { echo "pilot: no real accounts on the laptop stand to carry over" >&2; exit 1; }
  printf '%s\n' "$sql" | pilot exec -T db psql -U "$DB_USER" -d "$DB_NAME" -v ON_ERROR_STOP=1 >/dev/null
  # The seed makes a first owner on an empty database, from the address in
  # deploy/pilot.env and a password nobody knows. Once the real people are in
  # it has no reason to exist, and an owner account on a stand with a public
  # link has every reason not to.
  pilot exec -T db psql -U "$DB_USER" -d "$DB_NAME" -v ON_ERROR_STOP=1 -tAc \
    "DELETE FROM users WHERE email = '$(grep '^OWNER_EMAIL=' "$ENV_FILE" | cut -d= -f2)'" >/dev/null
  pilot exec -T db psql -U "$DB_USER" -d "$DB_NAME" -tAc "select '  ' || email || ' · ' || role from users order by email"
}

rows_in() {
  pilot exec -T db psql -U "$DB_USER" -d "$DB_NAME" -tAc "
    select coalesce(sum(n), 0) from (
      select count(*) n from customers union all select count(*) from vehicles
      union all select count(*) from rentals union all select count(*) from payments
      union all select count(*) from sales  union all select count(*) from purchases
    ) t" | tr -d ' '
}

tunnel() {
  # A quick tunnel: no account, no domain, a random hostname, and it lives
  # only as long as this run. When the Mac sleeps the registration is lost
  # and Cloudflare will not give the same hostname back — the container then
  # retries for ever against a name that no longer exists
  # ("Unauthorized: Tunnel not found"), which is what happened on 22.09. So
  # the old one is torn down rather than restarted, and the link is new every
  # time. A permanent address needs a Cloudflare account and a domain, which
  # is Mika's to set up.
  docker rm -f ev8-pilot-tunnel >/dev/null 2>&1 || true
  docker run -d --rm --name ev8-pilot-tunnel --network "${PILOT_PROJECT}_default" \
    cloudflare/cloudflared:latest tunnel --no-autoupdate --url http://web:5173 >/dev/null
  echo -n "pilot: waiting for the tunnel"
  for _ in $(seq 1 20); do
    # `|| true`: until the hostname appears grep exits 1, and with
    # `set -e pipefail` that would end the script on the first look.
    url=$(docker logs ev8-pilot-tunnel 2>&1 | grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' | head -1 || true)
    [ -n "${url:-}" ] && break
    echo -n .
    sleep 2
  done
  echo
  [ -n "${url:-}" ] || { echo "pilot: the tunnel did not report a hostname; docker logs ev8-pilot-tunnel" >&2; exit 1; }
  # `.trycloudflare.com` is already in ALLOWED_HOSTS, so a new hostname needs
  # no restart of web — without that the screen would say only "Blocked request".
  # Cloudflare prints the hostname before its edge is routing it; the first
  # few seconds answer nothing, which is not a fault of the stand.
  #
  # The check asks a public resolver for the address and dials that, rather
  # than trusting this Mac's own DNS. On 22.09 the resolver here (a VPN's,
  # 100.65.0.1) would not resolve *.trycloudflare.com at all, so a tunnel
  # that was serving the world perfectly well looked dead from the machine
  # running it. A check that reports the local resolver's opinion as the
  # tunnel's health is a check that lies.
  local code=000 ip=""
  for _ in $(seq 1 10); do
    ip=$(dig +short @1.1.1.1 "${url#https://}" 2>/dev/null | grep -m1 -E '^[0-9.]+$' || true)
    if [ -n "$ip" ]; then
      code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 20 --resolve "${url#https://}:443:$ip" "$url/" || true)
    fi
    [ "$code" = "200" ] && break
    sleep 3
  done
  echo "pilot: $url  (page $code)"
  if [ "$code" = "200" ]; then
    # Say it plainly when the link works everywhere except here.
    curl -s -o /dev/null --max-time 10 "$url/" 2>/dev/null ||
      echo "pilot: note — this Mac's own DNS does not resolve that name; the link works for others. Check with a phone." >&2
  else
    echo "pilot: the page did not answer 200 — check 'docker logs ev8-pilot-tunnel'" >&2
  fi
}

case "${1:-}" in
  up)
    make_env
    take_images
    empty_database
    # The API creates the tables on boot; the people go in after that.
    pilot up -d --no-build --force-recreate --wait api worker web
    echo "pilot: the people who may sign in —"
    copy_the_people
    echo "pilot: business records in this database: $(rows_in)"
    echo
    echo "Pilot stand: http://127.0.0.1:5195 — this Mac only, nothing else can reach it."
    echo "To show it to somebody, point a tunnel at that port, or at the compose"
    echo "network '${PILOT_PROJECT}_default', service 'web', port 5173."
    echo "Then add the hostname the tunnel gives to ALLOWED_HOSTS in deploy/pilot.env"
    echo "and restart web, or the screen says only 'Blocked request'."
    echo "Empty of content: Mika and Kardu fill it themselves. Demo logins refused."
    ;;
  tunnel) tunnel ;;
  down)
    docker rm -f ev8-pilot-tunnel >/dev/null 2>&1 || true
    pilot stop
    ;;
  status) pilot ps ;;
  *)
    echo "usage: scripts/pilot-stand.sh up | tunnel | down | status" >&2
    exit 2
    ;;
esac
